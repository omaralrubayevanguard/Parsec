        await pg.evaluate(SIGN(M)); await pg.wait_for_timeout(200)
        r = await pg.evaluate("[__tg.navAllowed('admin'), !!document.querySelector('[data-view=admin]')]")
        ok(r == [True, True], f"a manager does — they manage people ({r})")
