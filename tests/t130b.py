        # 1. who sees the Admin page
        r = await pg.evaluate("[__tg.navAllowed('admin'), !!document.querySelector('[data-action=nav][data-view=admin], [data-view=admin]')]")
        ok(r[0] and r[1], f"the Admin sees Admin in the sidebar ({r})")
