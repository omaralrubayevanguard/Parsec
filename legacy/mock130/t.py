import asyncio, os
from playwright.async_api import async_playwright
H = os.path.dirname(os.path.abspath(__file__))
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await (await b.new_context(viewport={"width":1440,"height":960})).new_page()
        errs = []; pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
        await pg.goto("file://" + H + "/mock.html"); await pg.wait_for_timeout(500)
        await pg.screenshot(path=H + "/s1_login.png")
        await pg.click("[data-who=dana]"); await pg.wait_for_timeout(300)
        for k in "12": await pg.keyboard.press(k)
        await pg.screenshot(path=H + "/s2_pin.png")
        for k in "99": await pg.keyboard.press(k)
        await pg.wait_for_timeout(200)
        print('msg', await pg.evaluate("document.querySelector('.pin .msg').textContent"))
        for k in "1234": await pg.keyboard.press(k)
        await pg.wait_for_timeout(700)
        print('toast', await pg.evaluate("(document.querySelector('.toast')||{}).textContent"))
        for lay in ['faces', 'type', 'badge']:
            await pg.click(f"[data-ch=lay][data-v={lay}]"); await pg.wait_for_timeout(250)
            await pg.screenshot(path=H + f"/s3_{lay}.png")
        await pg.click("[data-ch=lay][data-v=type]"); await pg.fill("#nm", "fr"); await pg.wait_for_timeout(200)
        print('sugg', await pg.evaluate("[...document.querySelectorAll('#sugg button')].map(b=>b.textContent)"))
        await pg.click("[data-scr=switch]"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=H + "/s4_switch.png")
        await pg.click(".menu [data-who=frank]"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=H + "/s5_switchpin.png")
        await pg.keyboard.press("Escape"); await pg.wait_for_timeout(200)
        await pg.click("[data-me]"); await pg.wait_for_timeout(200)
        await pg.click("[data-step]"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=H + "/s6_lock.png")
        await pg.click("[data-scr=admin]"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=H + "/s7_admin.png", full_page=True)
        await pg.click("[data-act='t.editall']"); await pg.wait_for_timeout(200)
        print('changed', await pg.evaluate("document.querySelectorAll('.sw em').length"))
        await pg.click("[data-adt=roles]"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=H + "/s8_roles.png", full_page=True)
        await pg.click("[data-adt=rules]"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=H + "/s9_rules.png")
        await pg.click("[data-adt=log]"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=H + "/s10_log.png")
        await pg.click("[data-dev=phone]"); await pg.click("[data-scr=login]"); await pg.click("[data-ch=lay][data-v=tiles]"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=H + "/s11_phone.png")
        await pg.click("#pk-open"); await pg.wait_for_timeout(200)
        print(await pg.evaluate("document.querySelector('#picks pre').textContent"))
        await pg.click("[data-th=graphite]"); await pg.click("[data-dev=desk]"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=H + "/s12_dark.png")
        print('errors', errs)
        await b.close()
asyncio.run(main())
