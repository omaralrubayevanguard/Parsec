import asyncio, sys
from playwright.async_api import async_playwright
F = sys.argv[1]; OUTD = sys.argv[2]; theme = sys.argv[3] if len(sys.argv) > 3 else 'light'
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); ctx = await b.new_context(viewport={"width":390,"height":844}, device_scale_factor=2, color_scheme=theme)
        pg = await ctx.new_page()
        errs=[]; pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("console", lambda m: errs.append(m.text) if m.type=="error" and "net::" not in m.text and "Failed to load" not in m.text else None)
        await pg.goto("file://"+F); await pg.wait_for_timeout(600)
        async def shot(n): await pg.wait_for_timeout(350); await pg.screenshot(path=f"{OUTD}/{theme}_{n}.png")
        await shot("01_welcome")
        await pg.click('[data-a="sample"]'); await shot("02_start")
        await pg.click('[data-a="clockin"]'); await shot("03_work")
        await pg.click('.ph-job[data-v="s1o1"] .go'); await pg.wait_for_timeout(200)
        await pg.evaluate("()=>{const S=__pm.S(); S.L.run.s=new Date(Date.now()-42*60000).toISOString(); S.L.shifts[0].in=new Date(Date.now()-95*60000).toISOString(); __pm.render();}")
        await shot("04_work_running")
        await pg.click('.ph-now .ph-job'); await shot("05_job_notes")
        await pg.fill('#noteIn', 'purge valve sticking, soapy water test confirms'); await pg.press('#noteIn', 'Enter'); await shot("06_note_added")
        await pg.click('[data-a="tab"][data-v="parts"]'); await shot("07_parts")
        await pg.click('[data-a="part"][data-v="0"]'); await shot("08_part_sheet")
        await pg.click('[data-a="pset"][data-v="Picked up"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-a="tab"][data-v="files"]'); await shot("09_files")
        await pg.click('[data-a="tab"][data-v="info"]'); await shot("10_info")
        await pg.click('.ph-acts .main'); await shot("11_stop_sheet")
        await pg.click('[data-a="pick"][data-v="Complete"]'); await shot("12_complete_needs_corr")
        await pg.click('[data-a="close"].ph-btn')
        await pg.click('[data-a="back"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-a="go"][data-v="inbox"]'); await shot("13_inbox")
        await pg.click('[data-a="go"][data-v="fixes"]'); await shot("14_fixes")
        await pg.click('.ph-fx.for'); await shot("15_fix_detail")
        await pg.click('[data-a="go"][data-v="work"]') if await pg.query_selector('[data-a="go"][data-v="work"]') else None
        await pg.click('[data-a="sheet"][data-v="clock"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-a="cpick"][data-v="End of day"]'); await shot("16_clockout_eod")
        await pg.click('[data-a="close"].ph-btn')
        await pg.click('.ph-syncchip'); await pg.click('[data-a="synct"][data-v="send"]'); await pg.wait_for_timeout(1500); await shot("17_sync_send")
        await pg.click('[data-a="synct"][data-v="get"]'); await pg.wait_for_timeout(600); await shot("18_sync_get")
        await pg.click('[data-a="back"]'); await pg.wait_for_timeout(200)
        await pg.click('.ph-top .ph-av'); await shot("19_me")
        print("errors:", errs)
        await b.close()
asyncio.run(main())
