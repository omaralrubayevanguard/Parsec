import asyncio, os
from playwright.async_api import async_playwright
H = os.path.dirname(os.path.abspath(__file__)); S = os.path.join(H, "shots")
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(viewport={"width": 1500, "height": 1000}); errs = []
        pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("console", lambda m: errs.append(m.text) if m.type == "error" and "ERR_" not in m.text else None)
        await pg.route("**/fonts.g*/**", lambda r: r.abort())
        await pg.goto("file://" + H + "/rp2.html"); await pg.wait_for_timeout(500)
        await pg.screenshot(path=os.path.join(S, "1_time.png"), full_page=True)
        await pg.click('[data-tm="p2:s"]'); await pg.wait_for_timeout(200)
        await pg.fill('[data-tin="p2:s"]', "12:00"); await pg.keyboard.press("Enter"); await pg.wait_for_timeout(200)
        await pg.click('[data-m="rs:p3:e"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=os.path.join(S, "2_reason_menu.png"))
        await pg.click('[data-rs="p3:e:Waiting – Parts"]'); await pg.wait_for_timeout(200)
        await pg.hover('.pu >> nth=1'); await pg.wait_for_timeout(100)
        await pg.click('.addb >> nth=0'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=os.path.join(S, "3_add.png"))
        await pg.click('[data-x="pfok"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-m="jt:o1"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=os.path.join(S, "4_jt.png"))
        await pg.keyboard.press("Escape")
        await pg.click('[data-tab="parts"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=os.path.join(S, "5_parts.png"))
        await pg.click('[data-ch="iSty"][data-v="word"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-ch="iWhat"][data-v="all"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=os.path.join(S, "6_words.png"))
        await pg.click('[data-thm="graphite"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-ch="thSz"][data-v="yes"]'); await pg.click('[data-tab="time"]'); await pg.click('[data-ch="tEd"][data-v="mode"]'); await pg.click('[data-x="alled"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=os.path.join(S, "7_dark_mode.png"), full_page=True)
        await pg.click('[data-x="mini"] >> nth=0'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=os.path.join(S, "8_mini.png"))
        await pg.click('[data-view="smp"]'); await pg.click('.mk [data-th="ivory"]'); await pg.wait_for_timeout(200)
        await pg.click('[data-ch="sSize"][data-v="wb"]'); await pg.click('[data-ch="sMore"][data-v="tr"]'); await pg.click('[data-ch="sFrom"][data-v="rnd"]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=os.path.join(S, "9_samples.png"))
        await pg.click('#pk-open'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=os.path.join(S, "10_picks.png"))
        pg2 = await b.new_page(viewport={"width": 390, "height": 844}); await pg2.goto("file://" + H + "/rp2.html"); await pg2.wait_for_timeout(400)
        await pg2.screenshot(path=os.path.join(S, "11_phone.png"), full_page=False)
        print("hscroll phone:", await pg2.evaluate("document.documentElement.scrollWidth > innerWidth"))
        print("ERRORS", errs); await b.close()
